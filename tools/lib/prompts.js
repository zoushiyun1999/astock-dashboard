function morningUser(date, articleUrl, text) {
  const md = date.slice(5).replace('-', '月') + '日';
  return [
    '以下是《' + md + '开盘必读资讯》正文（' + date + '），请整理成 JSON。',
    '',
    '【字段与条数要求】',
    '· 要闻简讯：5-12 条，每条一句话。',
    '· 盘前人气股：对象，四个键固定为 韭研公社 / 同花顺 / 东方财富 / 淘股吧；',
    '  原文没提到某个平台就留空字符串，**不要删键、不要换键名**。',
    '· 重点公告：**最多 12 条**，按对股价的影响从大到小排序。只挑这几类：',
    '  重组 / 收购 / 定增 / 复牌 / 立案调查 / 大额回购 / 业绩预告。',
    '  其中「减持」类最多留 3 条、「药品注册证书」类最多留 2 条。',
    '  ⚠️ **不要把原文的公告清单整段搬过来** —— 上一版列了 51 条，远超需要，属于失败产出。',
    '· 今日新股：一句话。',
    '· 今日关注：8 只左右，每项 {name, code, sector, status, reason}。',
    '',
    '【必须遵守的剥离规则】',
    '原文开头往往有一段编号目录（形如「1. 要闻简讯 2. 盘前人气股 3. 重点公告」）。',
    '**只剥离「开头连续递增的编号序列」这一段**；正文里的小标题必须保留。',
    '（历史教训：多剥一层会把正文小标题静默丢掉，整段内容消失。）',
    '',
    '【输出 JSON 的形状】（键名照抄，值按实际内容填）',
    JSON.stringify(MORNING_SHAPE, null, 2),
    '',
    '【原文开始】',
    text,
    '【原文结束】',
  ].join('\n');
}

