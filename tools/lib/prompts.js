/**
 * tools/lib/prompts.js —— 所有 LLM prompt 的集中定义
 *
 * 为什么集中：这些规则是长期踩坑沉淀下来的（status 三段式、板块热点与明日关注条数必须一致、
 * 剥离开头编号目录但不剥小标题…）。散落在各 job 脚本里必然漂移，改一处忘一处。
 * 调 prompt 只改这个文件。
 *
 * 边界约定（重要）：
 *   · **date / at / sourceUrl 一律由 job 脚本填**，不让模型产出 —— 模型不知道当前时间，一定会编。
 *   · 模型只负责「材料 → 结构化内容」这一段。
 */

/* ───────────────────────── 通用约束 ───────────────────────── */

const BASE_RULES = [
  '硬性要求：',
  '1. 只输出一个 JSON 对象。不要写解释文字、不要 markdown 围栏、不要任何前后缀。',
  '2. 严格使用给定字段名，不增不删、不加额外包装层。',
  '3. 内容必须来自输入材料，不要编造。材料里没有的：数组字段给 []，文字字段写「未提及」',
  '   （股票代码例外，见下条）。',
  '4. ⚠️ 禁止用占位符充数。`...`、`…`、`—`、`待补`、`N/A`、`xxx` 一类内容全视为无效；',
  '   文字字段必须是能直接展示给读者的完整短语，不留空、不写占位符。',
  '5. 股票代码必须是 6 位数字。不确定就填 ""，**绝对不要猜代码**（系统会另行校验，猜错会污染数据）。',
  '6. 保留材料里的原始表述与关键词，不要改写成通用套话。',
].join('\n');

