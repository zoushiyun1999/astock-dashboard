function eveningUser(date, materials) {
  const parts = [
    '以下是 ' + date + ' 的复盘材料。请整理成 JSON。',
    '',
    '【输出 JSON 的形状】（键名照抄；「明日关注」与「板块热点」条数必须一致）',
    JSON.stringify(EVENING_SHAPE, null, 2),
    '',
    '【条数提醒】明日关注 4-8 个板块，按强度降序；板块热点必须与它条数完全相同。',
    '',
    '【字段提醒】`picks[].code` 是唯一允许留空的字段（不确定就留空，系统会按名称回填）。',
    '其余所有文字字段一律不得留空、不得写 `...` 之类的占位符。',
    '',
  ];
  (materials || []).forEach(function (m) {
    parts.push('【材料：' + m.author + '（' + (m.kind || '文字') + '）开始】');
    parts.push(m.text || '（无内容）');
    parts.push('【材料：' + m.author + ' 结束】');
    parts.push('');
  });
  return parts.join('\n');
}

