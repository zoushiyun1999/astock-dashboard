function imageReadUser(date, author, batchIndex, batchTotal, files) {
  return [
    '博主：' + author + '　日期：' + date,
    '这是该博主当日复盘文章里的第 ' + (batchIndex + 1) + '/' + batchTotal + ' 批图片（共 ' + files.length + ' 张）。',
    '请逐张转录（顺序与你收到的图片顺序一致），每张图一个 block。',
    '若某张图与 A 股复盘无关，跳过它，不要为它生成 block。',
  ].join('\n');
}

