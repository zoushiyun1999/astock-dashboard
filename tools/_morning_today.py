# 读 data.js
content = DATA_FILE.read_text(encoding="utf-8")
# 匹配 window.REPORTS = {...};
m = re.match(r"window\.REPORTS\s*=\s*(\{.*\})\s*;\s*$", content, re.DOTALL)
if not m:
    raise SystemExit("data.js 格式不符合预期，无法解析")
data = json.loads(m.group(1))

# 更新 updatedAt
data["updatedAt"] = GEN_AT

# 找今天的 record
reports = data.get("reports", [])
today_idx = next((i for i, r in enumerate(reports) if r.get("date") == TODAY), None)

if today_idx is not None:
    rec = reports[today_idx]
    rec["morning"] = morning
else:
    reports.append({"date": TODAY, "morning": morning})

# 截断到最近 7 条
if len(reports) > 7:
    reports = reports[-7:]

data["reports"] = reports

# 写回（保持 window.REPORTS = {...}; 格式）
out = "window.REPORTS = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
DATA_FILE.write_text(out, encoding="utf-8")

